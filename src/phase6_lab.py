"""Phase 6: repeated real UE attempts with UTC windows for SBI correlation.

Every measurement is generated by the running Open5GS/UERANSIM lab.
No compromised SMF, malicious API messages, or subscriber identities
are generated. Windows link events by TIME only, not unique PDU ID.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import subprocess
import time
from datetime import datetime, timezone
from pathlib import Path

from .pdu_lab import trial, state, cmd


def run(compose_dir: Path, output: Path, *, repeats=6,
        normal_timeout=20., fail_timeout=12.):
    if os.environ.get("ALLOW_LAB_ONLY_SMF_FAILURE") != "yes":
        raise RuntimeError("Isolated laboratory SMF fault guard required")
    if "upstream_open5gs" not in str(compose_dir.resolve()):
        raise RuntimeError("Refusing non-laboratory container target")
    if repeats < 3:
        raise ValueError("At least three procedures per phase required")
    if not all(state(x) for x in ("nrf", "amf", "smf", "upf", "nr_gnb")):
        raise RuntimeError("5GC NF and radio access emulator must be running")
    output.mkdir(parents=True, exist_ok=True)
    entries = []

    def attempt(phase, index, max_seconds):
        # UTC wall clock shared with tcpdump; wide trial bounds include UE
        # container startup and teardown. The UE event itself is recognized
        # from real logs, not from the phase label.
        start = time.time()
        obs = trial(compose_dir, phase, index, max_seconds, 1.0)
        end = time.time()
        obs["window_start_epoch"] = start
        obs["window_end_epoch"] = end
        obs["window_duration_s"] = round(end - start, 4)
        entries.append(obs)

    try:
        for i in range(repeats):
            attempt("normal", i, normal_timeout)
        cmd(["docker", "stop", "-t", "1", "smf"], timeout=20)
        if state("smf"):
            raise RuntimeError("SMF still active after controlled stop")
        for i in range(repeats):
            attempt("smf_failstop", i, fail_timeout)
    finally:
        if not state("smf"):
            cmd(["docker", "start", "smf"], timeout=25)
    time.sleep(12)
    for i in range(repeats):
        attempt("recovery", i, normal_timeout)

    assert entries
    with (output / "real_pdu_windows.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(entries[0]))
        writer.writeheader()
        writer.writerows(entries)

    summary = {
        "source": "REAL Open5GS/ UERANSIM UE-log outcome plus UTC experiment windows",
        "temporal_linkage": "Capture frames between UTC start/end of one UE attempt",
        "unique_3gpp_procedure_join": False,
        "repeats_per_phase": repeats,
        "measurement_count": len(entries),
        "phases": {},
        "limitations": [
            "Window includes UE container startup and shutdown",
            "No globally unique UE-to-Nsmf correlation ID is exposed",
            "Retransmissions and proxy interactions may produce multiple frames per service",
            "No offensive NF manipulation: SMF fail-stop is controlled availability test",
        ],
    }
    for phase in ("normal", "smf_failstop", "recovery"):
        rows = [r for r in entries if r["phase"] == phase]
        summary["phases"][phase] = {
            "trials": len(rows),
            "ue_pdu_successes": sum(r["ue_pdu_session_accepted"] for r in rows),
            "ue_registered": sum(r["ue_registration_seen"] for r in rows),
            "smf_witness_up": sum(r["smf_running_witness"] for r in rows),
        }
    (output / "real_pdu_window_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    if not all(summary["phases"][phase]["ue_pdu_successes"] > 0 for phase in ("normal", "recovery")):
        raise RuntimeError("No observed successful UE session for normal or recovered SMF")
    if summary["phases"]["smf_failstop"]["ue_pdu_successes"] != 0:
        raise RuntimeError("Unexpected successful PDU establishment during SMF outage")
    return summary


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--compose-dir", type=Path, default=Path("upstream_open5gs"))
    ap.add_argument("--out", type=Path, default=Path("results/phase6"))
    ap.add_argument("--repeats", type=int, default=6)
    ns = ap.parse_args()
    print(json.dumps(run(ns.compose_dir, ns.out, repeats=ns.repeats),
                     ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
